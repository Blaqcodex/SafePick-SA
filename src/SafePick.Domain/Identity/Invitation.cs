using SafePick.Domain.Common;
using SafePick.Domain.Identity.Events;

namespace SafePick.Domain.Identity;

/// <summary>
/// A pending grant of authority.
///
/// An invitation is issued by an actor with sufficient authority
/// (Operator → School Admin, School Admin → School Staff) and redeemed
/// by the invitee, creating a User bound to a specific school.
///
/// An invitation is single-use and time-bounded. It is an aggregate root.
/// </summary>
public sealed class Invitation : AggregateRoot<Guid>
{
    public string Email { get; private set; }
    public Role Role { get; private set; }
    public Guid SchoolId { get; private set; }
    public InvitationToken Token { get; private set; }
    public InvitationStatus Status { get; private set; }
    public DateTime IssuedAt { get; private set; }
    public DateTime ExpiresAt { get; private set; }
    public DateTime? AcceptedAt { get; private set; }
    public Guid IssuedByUserId { get; private set; }

    private Invitation(
        Guid id,
        string email,
        Role role,
        Guid schoolId,
        InvitationToken token,
        DateTime issuedAt,
        DateTime expiresAt,
        Guid issuedByUserId) : base(id)
    {
        Email = email;
        Role = role;
        SchoolId = schoolId;
        Token = token;
        Status = InvitationStatus.Pending;
        IssuedAt = issuedAt;
        ExpiresAt = expiresAt;
        IssuedByUserId = issuedByUserId;
    }

    /// <summary>
    /// Issues a new invitation. The token must already be generated by
    /// the caller (infrastructure concern — cryptographic randomness).
    /// </summary>
    public static Invitation Issue(
        string email,
        Role role,
        Guid schoolId,
        InvitationToken token,
        TimeSpan validFor,
        Guid issuedByUserId,
        DateTime now)
    {
        if (role == Role.Operator)
            throw new DomainException("Operators cannot be invited.");

        if (validFor <= TimeSpan.Zero)
            throw new DomainException("Invitation validity must be positive.");

        var invitation = new Invitation(
            Guid.NewGuid(),
            email,
            role,
            schoolId,
            token,
            now,
            now.Add(validFor),
            issuedByUserId);

        invitation.Raise(new InvitationIssued(
            invitation.Id,
            invitation.Email,
            invitation.Role.ToString(),
            invitation.SchoolId,
            invitation.IssuedByUserId,
            now));

        return invitation;
    }

    /// <summary>
    /// Accepts the invitation. Only valid while Pending and within the
    /// expiry window. Marks the invitation as Accepted and returns the
    /// data needed to create the User.
    /// </summary>
    public void Accept(DateTime now)
    {
        if (Status != InvitationStatus.Pending)
            throw new DomainException(
                $"Cannot accept an invitation in status '{Status}'.");

        if (now > ExpiresAt)
        {
            Status = InvitationStatus.Expired;
            Raise(new InvitationExpired(Id, Email, ExpiresAt, now));
            throw new DomainException("Invitation has expired.");
        }

        Status = InvitationStatus.Accepted;
        AcceptedAt = now;
    }

    /// <summary>
    /// Marks the invitation expired if it is past its window.
    /// Called by the reconciliation process. Idempotent: does nothing
    /// if the invitation is not Pending or is still within the window.
    /// </summary>
    public void MarkExpired(DateTime now)
    {
        if (Status != InvitationStatus.Pending)
            return;

        if (now <= ExpiresAt)
            return;

        Status = InvitationStatus.Expired;
        Raise(new InvitationExpired(Id, Email, ExpiresAt, now));
    }

    /// <summary>
    /// Revokes a Pending invitation. Once revoked, the token is worthless.
    /// </summary>
    public void Revoke(Guid revokedByUserId, DateTime now)
    {
        if (Status != InvitationStatus.Pending)
            throw new DomainException(
                $"Cannot revoke an invitation in status '{Status}'.");

        Status = InvitationStatus.Revoked;
    }
}